// Traduce una clave al idioma dado. Fallback: inglés → la clave misma.
export function translate(key, lang) {
  const dict = TRANSLATIONS[lang] || TRANSLATIONS.en;
  return dict[key] ?? TRANSLATIONS.en[key] ?? key;
}

